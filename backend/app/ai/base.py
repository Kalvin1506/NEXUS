from abc import ABC,abstractmethod
from typing import Any

class AIProvider(ABC):
    name="base";model="none"
    @abstractmethod
    def normalize_ticket(self,ticket:dict[str,Any]):...
    @abstractmethod
    def extract_ticket_fields(self,ticket:dict[str,Any]):...
    @abstractmethod
    def classify_ticket(self,ticket:dict[str,Any]):...
    @abstractmethod
    def summarize_cases(self,evidence:dict[str,Any]):...
    @abstractmethod
    def draft_grounded_resolution(self,evidence:dict[str,Any]):...
    @abstractmethod
    def suggest_investigation_steps(self,ticket:dict[str,Any]):...
    @abstractmethod
    def generate_explanation(self,evidence:dict[str,Any]):...
    @abstractmethod
    def generate_handover(self,evidence:dict[str,Any]):...
    @abstractmethod
    def generate_kb_draft(self,evidence:dict[str,Any]):...

